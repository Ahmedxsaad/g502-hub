def update_ts():
    print(f"Reading {TS_FILE}...")
    tree = ET.parse(TS_FILE)
    root = tree.getroot()
    root.set("language", "zh_CN")

    translated_count = 0
    missing_count = 0

    for context in root.findall("context"):
        cname = context.find("name").text or ""
        for message in context.findall("message"):
            source = message.find("source").text
            comment_elem = message.find("comment")
            comment = comment_elem.text if comment_elem is not None else ""

            # Try exact match (context, source, comment)
            trans_text = TRANSLATIONS.get((cname, source, comment))
            # Fallback to ignore comment
            if trans_text is None:
                trans_text = TRANSLATIONS.get((cname, source, ""))
            # Fallback to ignore context
            if trans_text is None:
                trans_text = TRANSLATIONS.get(("", source, comment))
            # Fallback to pure source
            if trans_text is None:
                trans_text = TRANSLATIONS.get(("", source, ""))

            trans_elem = message.find("translation")
            if trans_text:
                if trans_elem is None:
                    trans_elem = ET.SubElement(message, "translation")
                trans_elem.text = trans_text
                if "type" in trans_elem.attrib:
                    del trans_elem.attrib["type"]
                translated_count += 1
            else:
                missing_count += 1
                print(f"MISSING: [{cname}] (comment: {comment}) -> {source}")

    tree.write(TS_FILE, encoding="utf-8", xml_declaration=True)
    print(f"Updated {TS_FILE}: {translated_count} translated, {missing_count} missing.")

    # Compile with lrelease
    lrelease_bin = "/usr/lib/qt6/bin/lrelease"
    print(f"Running {lrelease_bin} {TS_FILE} -qm {QM_FILE}...")
    res = subprocess.run([lrelease_bin, str(TS_FILE), "-qm", str(QM_FILE)], capture_output=True, text=True)
    print(res.stdout)
    if res.returncode != 0:
        print("ERROR in lrelease:", res.stderr)
        raise RuntimeError("lrelease failed")
    print("Done! QM file generated successfully.")


if __name__ == "__main__":
    update_ts()
